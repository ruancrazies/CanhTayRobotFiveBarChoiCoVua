# Set by the joint limits being all configured or all null; written as a constant of its own.
JOINT_LIMITS_CONFIGURED = "kJointLimitsConfigured"


def firmware_constants() -> dict[str, str]:
    """settings key -> the constant that carries it (for the reference report)."""
    found = {c.key: c.name for _, group in (*PINS, *CONFIG) for c in group}
    found["motion.joint_limits.alpha_min_deg"] = "kJointAlphaMinDeg"
    return found


def _float_literal(value: float) -> str:
    text = repr(float(value))
    if "." not in text and "e" not in text and "n" not in text:
        text += ".0"
    return text + "f"


def _render_value(constant: Constant, value: Any) -> str:
    if value is None:
        value = constant.when_null
    if constant.kind == "string":
        return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'
    if constant.kind == "level":
        return "true" if value == "HIGH" else "false"
    if constant.kind == "hex":
        return f"0x{int(value):02X}"
    if constant.ctype == "float":
        return _float_literal(value)
    if constant.ctype == "bool":
        return "true" if value else "false"
    number = int(value)
    limit = _TYPE_LIMITS.get(constant.ctype)
    if limit is not None and not 0 <= number <= limit:
        raise ValueError(f"{constant.key} = {number} does not fit {constant.ctype} ({constant.name})")
    return str(number)


def _describe(constant: Constant, raw: dict[str, Any], comments: dict[str, str], assumed: set[str]) -> list[str]:
    text = comments.get(constant.key, "").strip()
    lines = [f"// {constant.key}: {text}" if text else f"// {constant.key}"]
    if constant.key in assumed:
        lines.append("// ASSUMED: not confirmed on the real hardware (listed in `assumed` of settings.yaml).")
    if value_at(raw, constant.key) is None:
        lines.append("// null in settings.yaml: no value yet, so the constant is 0.")
    return lines


def _declaration(constant: Constant, rendered: str) -> str:
    if constant.ctype == "string":
        return f"constexpr char {constant.name}[] = {rendered};"
    return f"constexpr {constant.ctype} {constant.name} = {rendered};"


def _render_groups(groups: Sequence[tuple[str, tuple[Constant, ...]]], raw: dict[str, Any], comments: dict[str, str], assumed: set[str]) -> list[str]:
    out: list[str] = []
    for title, constants in groups:
        out.append(f"// ---- {title} " + "-" * max(3, 96 - len(title) - 8))
        for constant in constants:
            out.extend(_describe(constant, raw, comments, assumed))
            out.append(_declaration(constant, _render_value(constant, value_at(raw, constant.key))))
            if constant.name == "kJointBetaMaxDeg":
                out.append("// true when all four joint limits are set; false means no joint limit is known.")
                configured = all(value_at(raw, f"motion.joint_limits.{n}") is not None for n in ("alpha_min_deg", "alpha_max_deg", "beta_min_deg", "beta_max_deg"))
                out.append(f"constexpr bool {JOINT_LIMITS_CONFIGURED} = {'true' if configured else 'false'};")
        out.append("")
    return out


def _context(settings_path: Path) -> tuple[dict[str, Any], dict[str, str], set[str]]:
    load_settings(settings_path, overlay=False)  # the file must be valid before a header is written from it
    raw = load_raw(settings_path)
    comments = read_comments(settings_path.read_text(encoding="utf-8"))
    return raw, comments, set(raw.get("assumed") or [])


def render_pins_h(settings_path: Path = SETTINGS_PATH) -> str:
    raw, comments, assumed = _context(settings_path)
    body = _render_groups(PINS, raw, comments, assumed)
    lines = [
        BANNER.rstrip("\n"),
        "// ESP32 pin map: docs/SPEC.md section 4.2. The only place GPIO numbers are written.",
        "// Plain constants, no Arduino include, so host tests can include it.",
        "#ifndef CHESSBOT_PINS_H",
        "#define CHESSBOT_PINS_H",
        "",
        "#include <stdint.h>",
        "",
        "namespace chessbot {",
        "namespace pins {",
        "",
        *body,
        "}  // namespace pins",
        "}  // namespace chessbot",
        "",
        "#endif  // CHESSBOT_PINS_H",
        "",
    ]
    return "\n".join(lines)


def render_config_h(settings_path: Path = SETTINGS_PATH) -> str:
    raw, comments, assumed = _context(settings_path)
    body = _render_groups(CONFIG, raw, comments, assumed)
    lines = [
        BANNER.rstrip("\n"),
        "// Every firmware tunable lives here (SPEC rule 7); pin numbers live in pins.h, the wire protocol in",
        "// protocol.h. Plain constants, no Arduino include, so host tests can include it.",
        "//",
        "// A value marked ASSUMED is not confirmed on the real hardware. A value of 0 that says \"null\" is not decided:",
        "// the stage that needs it must refuse to run until it is set.",
        "#ifndef CHESSBOT_CONFIG_H",
        "#define CHESSBOT_CONFIG_H",
        "",
        "#include <stdint.h>",
        "",
        "namespace chessbot {",
        "namespace config {",
        "",
        *body,
        "}  // namespace config",
        "}  // namespace chessbot",
        "",
        "#endif  // CHESSBOT_CONFIG_H",
        "",
    ]
    return "\n".join(lines)


def generated_files(settings_path: Path = SETTINGS_PATH) -> dict[Path, str]:
    """Every file this generator owns, as the text it would write."""
    return {PINS_H: render_pins_h(settings_path), CONFIG_H: render_config_h(settings_path)}


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Generate firmware/include/pins.h and config.h from config/settings.yaml.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when a committed header is stale")
    args = parser.parse_args(argv)
    stale = 0
    for path, text in generated_files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != text:
                stale += 1
                sys.stderr.write(f"STALE: {path.relative_to(REPO_ROOT)} differs from config/settings.yaml; run: python -m tools.gen_all\n")
        elif current != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            sys.stdout.write(f"wrote {path.relative_to(REPO_ROOT)}\n")
        else:
            sys.stdout.write(f"unchanged {path.relative_to(REPO_ROOT)}\n")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
