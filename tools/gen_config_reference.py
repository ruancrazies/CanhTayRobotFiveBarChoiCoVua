"""Generate docs/CONFIG_REFERENCE.md: every key of config/settings.yaml with its value, unit and status.

    python -m tools.gen_config_reference            # write the report
    python -m tools.gen_config_reference --check    # exit 1 when the committed report is stale

The report is generated from the committed settings.yaml alone (config/local.yaml is never read).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Optional, Sequence

from desktop_app.utils.settings import REPO_ROOT, load_settings
from tools.gen_firmware_config import SETTINGS_PATH, firmware_constants
from tools.settings_doc import leaf_paths, load_documentation, unit_of, value_at

REFERENCE_PATH = REPO_ROOT / "docs" / "CONFIG_REFERENCE.md"

HEADER = """<!-- GENERATED by tools/gen_config_reference.py from config/settings.yaml. GENERATED, do not edit. -->
<!-- To change a value, edit config/settings.yaml and run:  python -m tools.gen_all -->

# Configuration reference

Every changeable value of the robot lives in `config/settings.yaml` (docs/SPEC.md rule 7 and section 4). This page is
generated from that file: one row per value, with its unit (from the key name), whether it is in `assumed` (not
confirmed on the real hardware; the owner replaces it later), the firmware constant that carries it, and the comment
written next to it in the file.

- **assumed**: `yes` means the key is listed under `assumed:` in settings.yaml.
- **null** means no value yet. Code that needs it refuses to run (PC) or uses 0 (firmware constant) until it is set.
- Per-machine values (Stockfish path, serial port) are overridden in `config/local.yaml` (git-ignored); the
  `STOCKFISH_PATH` environment variable comes first. Neither is shown here.
"""


def _format_value(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (dict, list)):
        return json.dumps(value, ensure_ascii=False, separators=(", ", ": "))
    return str(value)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_reference(settings_path: Path = SETTINGS_PATH) -> str:
    load_settings(settings_path, overlay=False)
    raw, comments = load_documentation(settings_path)
    assumed = set(raw.get("assumed") or [])
    carried = firmware_constants()
    paths = leaf_paths(raw)

    sections: dict[str, list[str]] = {}
    for dotted in paths:
        sections.setdefault(dotted.split(".")[0], []).append(dotted)

    lines = [HEADER.rstrip("\n"), ""]
    lines.append(f"{len(paths)} values, {len(assumed)} of them assumed.")
    lines.append("")
    for section, keys in sections.items():
        lines.append(f"## {section}")
        lines.append("")
        lines.append("| Key | Value | Unit | Assumed | Firmware constant | Description |")
        lines.append("|---|---|---|---|---|---|")
        for dotted in keys:
            constant = carried.get(dotted, "")
            lines.append(
                "| `{k}` | `{v}` | {u} | {a} | {c} | {d} |".format(
                    k=dotted,
                    v=_cell(_format_value(value_at(raw, dotted))),
                    u=unit_of(dotted),
                    a="yes" if dotted in assumed else "",
                    c=f"`{constant}`" if constant else "",
                    d=_cell(comments.get(dotted, "")),
                )
            )
        lines.append("")
    lines.append("## assumed")
    lines.append("")
    lines.append("Every key below exists in settings.yaml (a test enforces it) and is not yet confirmed on the real hardware.")
    lines.append("")
    for dotted in sorted(assumed):
        lines.append(f"- `{dotted}`")
    lines.append("")
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/CONFIG_REFERENCE.md from config/settings.yaml.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when the committed report is stale")
    args = parser.parse_args(argv)
    text = render_reference()
    current = REFERENCE_PATH.read_text(encoding="utf-8") if REFERENCE_PATH.exists() else None
    if args.check:
        if current != text:
            sys.stderr.write("STALE: docs/CONFIG_REFERENCE.md differs from config/settings.yaml; run: python -m tools.gen_all\n")
            return 1
        return 0
    if current != text:
        REFERENCE_PATH.write_text(text, encoding="utf-8", newline="\n")
        sys.stdout.write("wrote docs/CONFIG_REFERENCE.md\n")
    else:
        sys.stdout.write("unchanged docs/CONFIG_REFERENCE.md\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
